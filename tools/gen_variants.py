KIND_TYPE = {"flow":"support","push":"refute","meta":"qualify"}

# --- нарезаем сегменты по якорям ------------------------------------------
prev=-1; pos=[]
for a,*_ in T:
    i=next(j for j,l in enumerate(LINES) if j>prev and a.lower() in l.lower()); pos.append(i); prev=i
pos.append(len(LINES))

def clean(block):
    out=[]
    for l in block:
        s=l.strip()
        if s.lower() in SKIP: continue
        if re.fullmatch(r'https?://\S+', s, re.I): continue
        out.append(s)
    return [x for x in out if x]

segs=[]
for k in range(len(T)):
    a,thesis,topic,branch,kind = T[k]
    block = LINES[pos[k]:pos[k+1]]
    block = clean(block)
    # делим на реплику Алекса и ответ ИИ: ответ ИИ начинается с первой длинной строки
    ai_start = next((idx for idx,l in enumerate(block) if len(l)>140), None)
    if ai_start is None:
        user_lines, ai_lines = block, []
    else:
        user_lines, ai_lines = block[:ai_start], block[ai_start:]
    src = "gemini" if k < 42 else "claude"
    segs.append(dict(i=k, thesis=thesis, topic=topic, branch=branch, kind=kind,
                     src=src, user="\n".join(user_lines).strip(),
                     ai="\n".join(ai_lines).strip()))

def first_phrase(text, n=40):
    t = " ".join(text.split())
    return (t[:n] + "…") if len(t) > n else t

# === Вариант 1: ПО ТЕМАМ (группируем подряд идущие по branch) =============
def variant_topics():
    nodes=[]; links=[]; groups=[]
    cur=None
    for s in segs:
        if cur is None or s["branch"]!=cur["branch"]:
            cur=dict(branch=s["branch"], topic=s["topic"], src=s["src"],
                     thesis=s["thesis"], kind=s["kind"], parts=[])
            groups.append(cur)
        cur["parts"].append(s)
    for gi,g in enumerate(groups, start=1):
        body=[]
        for s in g["parts"]:
            if s["user"]: body.append("▸ "+s["user"])
            if s["ai"]:   body.append(s["ai"])
        text="\n\n".join(body)
        nodes.append(dict(id=gi, text=text, topic=g["branch"], turn=gi, source=g["src"],
                          branch=g["branch"]))
        if gi>1:
            links.append(dict(source=gi, target=gi-1, type=KIND_TYPE[g["kind"]], thesis=g["thesis"]))
    return dict(nodes=nodes, links=links,
                meta=dict(name="По темам", note=f"{len(nodes)} узлов · узел = тема целиком (вопросы + ответы ИИ дословно)"))

# === Вариант 2: ПО РЕПЛИКАМ (каждое сообщение — узел) =====================
def variant_messages():
    nodes=[]; links=[]; nid=0; prev_id=None
    for s in segs:
        if s["user"]:
            nid+=1; u_id=nid
            nodes.append(dict(id=u_id, text=s["user"], topic="Алекс: "+first_phrase(s["user"],28),
                              turn=nid, source="alex", branch=s["branch"]))
            if prev_id: links.append(dict(source=u_id, target=prev_id, type="qualify", thesis=s["thesis"]))
            prev_id=u_id
        if s["ai"]:
            nid+=1; a_id=nid
            nodes.append(dict(id=a_id, text=s["ai"], topic=s["src"].capitalize()+": "+first_phrase(s["ai"],26),
                              turn=nid, source=s["src"], branch=s["branch"]))
            if prev_id: links.append(dict(source=a_id, target=prev_id, type=KIND_TYPE[s["kind"]], thesis=s["thesis"]))
            prev_id=a_id
    return dict(nodes=nodes, links=links,
                meta=dict(name="По репликам", note=f"{len(nodes)} узлов · каждое сообщение отдельно"))

# === Вариант 3: УЗЕЛ = ОТВЕТ ИИ, ребро = тезис Алекса =====================
def variant_answers():
    nodes=[]; links=[]; prev_id=None; nid=0
    for s in segs:
        if not s["ai"]:
            continue
        nid+=1
        nodes.append(dict(id=nid, text=s["ai"], topic=s["topic"], turn=nid, source=s["src"], branch=s["branch"]))
        if prev_id:
            links.append(dict(source=nid, target=prev_id, type=KIND_TYPE[s["kind"]], thesis=s["thesis"]))
        prev_id=nid
    return dict(nodes=nodes, links=links,
                meta=dict(name="Узел = ответ ИИ", note=f"{len(nodes)} узлов · на рёбрах — тезисы Алекса"))

for fname, fn in [("topics",variant_topics),("messages",variant_messages),("answers",variant_answers)]:
    data=fn()
    json.dump(data, open(f"{OUT}/{fname}.json","w",encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"{fname:9s}: {len(data['nodes']):>3} узлов, {len(data['links']):>3} рёбер — {data['meta']['note']}")
