# ---------------------------------------------------------------- индексы
DOMAIN_BY_ID = {d["id"]: d for d in DOMAINS}
SUBS_BY_DOMAIN = {d["id"]: set(d["subs"]) for d in DOMAINS}

COUNTRIES = sorted({c for cont in GEO_TREE
                    for r in cont["regions"] for c in r["countries"]})
REGION_NAMES = {r["name"] for cont in GEO_TREE for r in cont["regions"]}
CONTINENT_NAMES = {c["name"] for c in GEO_TREE}
UNION_NAMES = {u["name"] for u in GEO_UNIONS}

# Страна -> все её регионы и части света. Множественное родительство здесь и
# живёт: у России их два, и оба сохраняются.
GEO_PARENTS: dict[str, dict[str, set]] = {}
for _cont in GEO_TREE:
    for _r in _cont["regions"]:
        for _c in _r["countries"]:
            slot = GEO_PARENTS.setdefault(_c, {"regions": set(), "continents": set()})
            slot["regions"].add(_r["name"])
            slot["continents"].add(_cont["name"])

# Всё, что вообще допустимо положить в гео-метку темы.
VALID_GEO = set(COUNTRIES) | REGION_NAMES | CONTINENT_NAMES | UNION_NAMES


def geo_closure(names):
    """Страна тянет за собой ВСЕ свои регионы и части света.

    Благодаря множественному родительству тема про Россию находится и по
    «Европа», и по «Азия» — ради этого замыкание и считается на записи, а не
    на чтении: фильтр по континенту остаётся одним индексным сравнением.
    """
    out = set()
    for n in names or []:
        if n not in VALID_GEO:
            continue
        out.add(n)
        p = GEO_PARENTS.get(n)
        if p:
            out |= p["regions"]
            out |= p["continents"]
    return out


def validate(domain, sub, geo, tags):
    """Возвращает (domain, sub, geo[], tags[]) или бросает ValueError.

    Клиент не в доверенных: рубрику, которой нет в таксономии, принимать
    нельзя — иначе фасеты со временем зарастут мусором и опечатками.
    """
    if domain not in DOMAIN_BY_ID:
        raise ValueError(f"неизвестное направление: {domain!r}")
    if sub and sub not in SUBS_BY_DOMAIN[domain]:
        raise ValueError(f"подветвь {sub!r} не принадлежит направлению {domain!r}")
    bad = [g for g in (geo or []) if g not in VALID_GEO]
    if bad:
        raise ValueError("неизвестная география: " + ", ".join(bad[:3]))
    clean_tags = []
    for t in (tags or []):
        t = " ".join(str(t).split()).strip().lower()[:40]
        if t and t not in clean_tags:
            clean_tags.append(t)
    return domain, (sub or None), sorted(set(geo or [])), clean_tags[:8]


def as_dict():
    """То, что отдаётся фронту одним куском."""
    return {"domains": DOMAINS, "geo_tree": GEO_TREE, "unions": GEO_UNIONS,
            "countries": COUNTRIES}
