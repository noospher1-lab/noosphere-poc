// Общее HTML-экранирование для всех страниц. Подключается ПЕРВЫМ скриптом.
//
// Правило (задание безопасности 05.10.2026): всё, что пришло с сервера и не
// является константой из кода, — недоверенный текст. В разметку-строку он
// попадает только через escHtml(); где можно — через textContent.
// Экранирование делается при ВЫВОДЕ, а не при записи: опубликованное не правим.
function escHtml(s) {
  return String(s ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));
}

// Подсветка совпадений с запросом. Исходный текст делится по совпадениям,
// КАЖДЫЙ кусок экранируется отдельно, совпадения оборачиваются в <mark>.
// Поэтому запрос «amp» не лезёт внутрь «&amp;»: ищем в сыром тексте, а не в
// уже экранированной строке.
function escHighlight(text, query) {
  const s = String(text ?? "");
  if (!query) return escHtml(s);
  const re = new RegExp("(" + query.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + ")", "gi");
  return s.split(re).map((part, i) =>
    i % 2 ? "<mark>" + escHtml(part) + "</mark>" : escHtml(part)).join("");
}

// Ссылка из данных людей (источник, масштаб, реестр) → только http(s).
// Иначе `javascript:`-адрес в href исполняется по клику в нашем origin.
// Не http(s) → "" (вызывающий не ставит href и показывает текст без ссылки).
function safeUrl(u) {
  try {
    const x = new URL(String(u ?? "").trim(), location.origin);
    return x.protocol === "http:" || x.protocol === "https:" ? x.href : "";
  } catch (_) { return ""; }
}
